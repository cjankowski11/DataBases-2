    v_inserted INT := 0;
    v_attempts INT := 0;
    j INT;
    v_receptionist_id INT;
    v_client_id INT;
    v_article_id INT;
    v_random_date DATE;
    v_max_trans_id INT;
    v_num_articles INT;
    v_qty INT;
    v_success BOOLEAN;
BEGIN
    SELECT employee_id INTO v_receptionist_id FROM receptionist LIMIT 1;
