            v_success := TRUE;
        EXCEPTION
            WHEN OTHERS THEN
                v_success := FALSE;
        END;

        IF NOT v_success THEN
            CONTINUE;
        END IF;

        v_max_trans_id := v_max_trans_id + 1;
        v_num_articles := 1 + (RANDOM() * 2)::INT;

        FOR j IN 1..v_num_articles LOOP
            SELECT article_id INTO v_article_id FROM article ORDER BY RANDOM() LIMIT 1;
